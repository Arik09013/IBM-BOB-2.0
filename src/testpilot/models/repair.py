"""
Failure analysis and repair data models for TestPilot AI.

These Pydantic models represent the structured output produced by the
FailureAnalysisAgent, RepairAgent, and the iterative repair loop.

Design rules:
  - Every field has a sensible default so partial construction is safe.
  - All Path fields are stored as strings for JSON serialisation compatibility.
  - No secrets, credentials, or API keys are stored.
  - Distinguishes generated-test defects from real source-code bugs.
  - Tracks bounded iterations, diffs, and verification outcomes explicitly.
"""

from __future__ import annotations

from datetime import UTC, datetime
from enum import StrEnum

from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class FailureCategory(StrEnum):
    """Classification of a test failure."""

    GENERATED_TEST_ISSUE = "generated_test_issue"
    """The generated test has a bug (e.g. incorrect call syntax, wrong types)."""

    INCORRECT_EXPECTATION = "incorrect_expectation"
    """The test asserted an incorrect expected value or condition for valid behavior."""

    MISSING_FIXTURE_IMPORT_SETUP = "missing_fixture_import_setup"
    """A missing import, missing pytest fixture, or uninitialized dependency."""

    SOURCE_CODE_DEFECT = "source_code_defect"
    """The test exposed a genuine bug or unhandled exception in the source code under test."""

    ENVIRONMENT_DEPENDENCY_ISSUE = "environment_dependency_issue"
    """Execution failed due to missing system package, file permission, or environment issue."""

    UNKNOWN = "unknown"
    """Failure could not be definitively classified."""


class RepairStatus(StrEnum):
    """Overall outcome of a repair loop run."""

    SUCCESS = "success"
    """All failing tests were repaired and verified passing via re-execution."""

    PARTIAL = "partial"
    """Some failing tests were fixed, but others remain."""

    NOT_REPAIRABLE = "not_repairable"
    """Failures are caused by source-code defects or environment issues, not test code."""

    VALIDATION_FAILED = "validation_failed"
    """Generated repair code failed AST syntax or structure validation."""

    MAX_ITERATIONS_EXCEEDED = "max_iterations_exceeded"
    """Maximum bounded repair attempts reached without resolving all failures."""

    NO_FAILURES = "no_failures"
    """No test failures were detected upon initial execution."""

    LLM_ERROR = "llm_error"
    """An error occurred while communicating with the LLM provider."""

    VALIDATION_ERROR = "validation_error"
    """Input parameters or paths were invalid."""

    ERROR = "error"
    """An unexpected fatal repair error occurred."""


# ---------------------------------------------------------------------------
# Sub-models
# ---------------------------------------------------------------------------

class FailureAnalysis(BaseModel):
    """Diagnostic analysis of a single failing test case."""

    test_nodeid: str
    """Canonical test identifier (e.g. 'tests/test_calc.py::test_division')."""

    category: FailureCategory = FailureCategory.UNKNOWN
    """Classified category of the failure."""

    confidence: float = 1.0
    """Confidence score in this classification (0.0 - 1.0)."""

    is_repairable_at_test_level: bool = True
    """True if the failure can be resolved by modifying test code without hiding bugs."""

    explanation: str = ""
    """Detailed plain-language explanation of why the test failed."""

    suggested_fix: str = ""
    """Recommended code change or adjustment."""

    root_cause: str = ""
    """Identified root cause (e.g. 'ZeroDivisionError not caught by pytest.raises')."""

    failure_type: str = ""
    """Exception type reported by runner (e.g. 'AssertionError', 'NameError')."""

    failure_message: str = ""
    """Original failure message from test output."""


class RepairAttemptRecord(BaseModel):
    """Record of a single repair cycle in the bounded repair loop."""

    iteration: int
    """1-based iteration number of this attempt."""

    test_file: str
    """Repository-relative path of the test file being repaired."""

    original_failures: list[str] = Field(default_factory=list)
    """Node IDs of tests that were failing at the start of this iteration."""

    analyses: list[FailureAnalysis] = Field(default_factory=list)
    """Diagnostic analyses for the failures in this iteration."""

    repaired_code: str = ""
    """Candidate repaired Python test code generated by the LLM."""

    patch_diff: str = ""
    """Unified diff showing changes from original to repaired code."""

    is_ast_valid: bool = False
    """Whether the candidate repaired code passed AST syntax validation."""

    validation_error: str | None = None
    """Error message if AST validation failed."""

    re_execution_passed: bool = False
    """True if re-executing pytest on the repaired file passed with zero failures."""

    remaining_failures: list[str] = Field(default_factory=list)
    """Node IDs of tests that still failed after re-execution."""

    duration_seconds: float = 0.0
    """Duration of this repair attempt in seconds."""


# ---------------------------------------------------------------------------
# Top-level Repair Report
# ---------------------------------------------------------------------------

class RepairReport(BaseModel):
    """
    Complete structured report of a failure analysis and repair run.

    Created by RepairAgent / run_repair_loop().
    Stored in SessionContext.repair_report and persisted as JSON.
    """

    repository_path: str
    test_file: str = ""
    status: RepairStatus = RepairStatus.ERROR

    started_at: datetime = Field(
        default_factory=lambda: datetime.now(tz=UTC)
    )
    completed_at: datetime | None = None
    duration_seconds: float = 0.0

    iterations_run: int = 0
    max_iterations: int = 2

    initial_failures: list[str] = Field(default_factory=list)
    final_failures: list[str] = Field(default_factory=list)

    analyses: list[FailureAnalysis] = Field(default_factory=list)
    attempts: list[RepairAttemptRecord] = Field(default_factory=list)
    repaired_files: list[str] = Field(default_factory=list)

    errors: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)

    # ------------------------------------------------------------------
    # Convenience properties
    # ------------------------------------------------------------------

    @property
    def resolved(self) -> bool:
        """True when all failures were successfully resolved or none were present."""
        if self.status in (RepairStatus.SUCCESS, RepairStatus.NO_FAILURES):
            return True
        if self.status in (
            RepairStatus.NOT_REPAIRABLE,
            RepairStatus.VALIDATION_FAILED,
            RepairStatus.MAX_ITERATIONS_EXCEEDED,
            RepairStatus.ERROR,
            RepairStatus.LLM_ERROR,
            RepairStatus.VALIDATION_ERROR,
        ):
            return False
        return len(self.initial_failures) > 0 and len(self.final_failures) == 0

    @property
    def failures_fixed_count(self) -> int:
        """Count of tests that were failing initially but now pass."""
        return max(0, len(self.initial_failures) - len(self.final_failures))

    @property
    def has_source_code_defects(self) -> bool:
        """True if any failure was identified as a genuine bug in source code."""
        return any(a.category == FailureCategory.SOURCE_CODE_DEFECT for a in self.analyses)
